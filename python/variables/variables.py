# =============================================================
# 변수 (Variables)
# =============================================================
# 변수란 데이터를 저장하는 이름표입니다.
# Python에서는 변수 선언 시 타입을 따로 적지 않습니다.

# 변수 만들기
name = "Alice"          # 문자열(str)
age = 20                # 정수(int)
height = 165.5          # 실수(float)
is_student = True       # 논리값(bool)

print(name)             # Alice
print(age)              # 20
print(height)           # 165.5
print(is_student)       # True

# =============================================================
# 변수 이름 규칙
# =============================================================
# - 영문자, 숫자, 밑줄(_) 사용 가능
# - 숫자로 시작할 수 없음
# - 대소문자 구별 (name ≠ Name)

my_score = 95           # 올바른 이름
MY_SCORE = 95           # 상수처럼 쓸 때 관례적으로 대문자 사용
# 2score = 95           # 오류! 숫자로 시작 불가

# =============================================================
# 변수 값 변경
# =============================================================
count = 0
print(count)            # 0

count = count + 1       # 1 증가
print(count)            # 1

count += 1              # 위와 동일한 표현 (복합 대입 연산자)
print(count)            # 2

# =============================================================
# 여러 변수를 한 줄에 할당
# =============================================================
x, y, z = 1, 2, 3
print(x, y, z)          # 1 2 3

a = b = 10              # a와 b 모두 10
print(a, b)             # 10 10

# =============================================================
# 변수 타입 확인
# =============================================================
print(type(name))       # <class 'str'>
print(type(age))        # <class 'int'>
print(type(height))     # <class 'float'>
print(type(is_student)) # <class 'bool'>
