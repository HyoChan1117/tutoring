# =============================================================
# 조건문 (Conditionals)
# =============================================================
# 조건에 따라 다른 코드를 실행합니다.
# Python은 들여쓰기(4칸 또는 탭)로 블록을 구분합니다.

# =============================================================
# 1. if — 조건이 True일 때만 실행
# =============================================================
score = 75

if score >= 60:
    print("합격")           # 75 >= 60 이므로 실행

# 조건이 False면 if 블록은 통째로 건너뜀
if score >= 90:
    print("장학금 대상")    # 실행 안 됨

# =============================================================
# 2. if-else — 참 / 거짓 두 갈래
# =============================================================
temperature = 15

if temperature >= 20:
    print("반팔을 입으세요")
else:
    print("긴팔을 입으세요")   # 15 < 20 이므로 여기 실행

# =============================================================
# 3. if-elif-else — 여러 조건을 위에서부터 순서대로 검사
# =============================================================
# 처음으로 True인 블록 하나만 실행되고 나머지는 건너뜁니다.

score = 85

if score >= 90:
    grade = "A"
elif score >= 80:           # 85 >= 80 → 여기서 True, 이 블록 실행
    grade = "B"
elif score >= 70:           # 앞에서 이미 실행됐으므로 검사 안 함
    grade = "C"
elif score >= 60:
    grade = "D"
else:
    grade = "F"

print(f"점수: {score}, 학점: {grade}")  # 점수: 85, 학점: B

# =============================================================
# 4. 비교 연산자
# =============================================================
a, b = 10, 20

print(a == b)   # False  같다
print(a != b)   # True   다르다
print(a < b)    # True   작다
print(a > b)    # False  크다
print(a <= b)   # True   작거나 같다
print(a >= b)   # False  크거나 같다

# =============================================================
# 5. 논리 연산자 (and / or / not)
# =============================================================
age = 20
has_ticket = True

# and : 양쪽 모두 True여야 True
if age >= 18 and has_ticket:
    print("입장 가능")

# or : 하나라도 True면 True
is_weekend = True
is_holiday = False

if is_weekend or is_holiday:
    print("쉬는 날입니다")

# not : True → False, False → True
is_raining = False

if not is_raining:
    print("우산 필요 없음")

# 복합 사용
x = 15
if x > 0 and (x % 2 == 0 or x > 10):
    print(f"{x}는 양수이고, 짝수이거나 10 초과")   # 실행됨

# =============================================================
# 6. in / not in — 포함 여부 확인
# =============================================================
fruits = ["apple", "banana", "cherry"]

if "banana" in fruits:
    print("바나나 있음")

if "mango" not in fruits:
    print("망고 없음")

# 문자열에도 사용 가능
email = "user@yju.ac.kr"

if "@" in email:
    print("유효한 이메일 형식")

# =============================================================
# 7. 중첩 if — if 안에 if
# =============================================================
num = 15

if num > 0:
    print("양수")
    if num % 2 == 0:
        print("짝수")
    else:
        print("홀수")       # 15는 홀수 → 여기 실행
else:
    print("0 또는 음수")

# =============================================================
# 8. 조건부 표현식 (삼항 연산자)
# =============================================================
# 형식: 참일_때_값 if 조건 else 거짓일_때_값
# 간단한 if-else를 한 줄로 작성할 때 사용

n = 7
result = "짝수" if n % 2 == 0 else "홀수"
print(result)               # 홀수

# 변수 할당뿐 아니라 출력에도 바로 사용 가능
age = 20
print("성인" if age >= 18 else "미성년자")   # 성인

# =============================================================
# 실전 예제: 도서관 이용권 판별 (lab 1번 참고)
# =============================================================
age = 16   # 직접 값을 넣어 테스트

if age <= 12:
    ticket = "어린이 이용권"
elif age <= 18:
    ticket = "청소년 이용권"
else:
    ticket = "성인 이용권"

print(f"{ticket}을 사용할 수 있습니다.")    # 청소년 이용권을 사용할 수 있습니다.
