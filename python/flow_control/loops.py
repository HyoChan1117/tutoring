# =============================================================
# 반복문 (Loops)
# =============================================================
# 같은 코드를 여러 번 실행할 때 사용합니다.
# Python의 반복문은 for와 while 두 가지입니다.

# =============================================================
# 1. for — 정해진 횟수나 컬렉션을 순서대로 반복
# =============================================================
fruits = ["apple", "banana", "cherry"]

for fruit in fruits:
    print(fruit)
# apple
# banana
# cherry

# 문자열도 순회 가능 (한 글자씩)
for char in "Hello":
    print(char, end=" ")    # H e l l o
print()

# =============================================================
# 2. range() — 숫자 범위 반복
# =============================================================
# range(끝)           → 0 ~ 끝-1
# range(시작, 끝)     → 시작 ~ 끝-1
# range(시작, 끝, 간격)

for i in range(5):
    print(i, end=" ")       # 0 1 2 3 4
print()

for i in range(1, 6):
    print(i, end=" ")       # 1 2 3 4 5
print()

for i in range(0, 10, 2):
    print(i, end=" ")       # 0 2 4 6 8
print()

for i in range(5, 0, -1):
    print(i, end=" ")       # 5 4 3 2 1
print()

# =============================================================
# 3. enumerate() — 인덱스와 값을 함께 가져오기
# =============================================================
subjects = ["수학", "영어", "과학"]

for index, subject in enumerate(subjects):
    print(f"{index + 1}번: {subject}")
# 1번: 수학
# 2번: 영어
# 3번: 과학

# =============================================================
# 4. while — 조건이 True인 동안 반복
# =============================================================
count = 0
while count < 5:
    print(count, end=" ")   # 0 1 2 3 4
    count += 1              # 반드시 조건을 바꿔줘야 무한루프 방지
print()

# 합계 구하기
total = 0
n = 1
while n <= 100:
    total += n
    n += 1
print(f"1~100 합계: {total}")   # 5050

# =============================================================
# 5. break — 반복문 즉시 탈출
# =============================================================
# 특정 조건을 만족하면 반복을 멈추고 싶을 때 사용

numbers = [3, 7, 2, 9, 1, 5]

for num in numbers:
    if num > 5:
        print(f"5 초과 첫 번째 수: {num}")  # 5 초과 첫 번째 수: 7
        break                               # 찾으면 바로 종료

# while + break 조합 (무한 루프 탈출)
count = 0
while True:
    count += 1
    if count == 3:
        break
print(f"count: {count}")    # count: 3

# =============================================================
# 6. continue — 현재 회차만 건너뛰고 다음 반복 진행
# =============================================================
# break는 반복 전체를 끝내고, continue는 이번 회차만 스킵

for i in range(1, 11):
    if i % 2 != 0:
        continue            # 홀수면 아래 print를 건너뜀
    print(i, end=" ")       # 2 4 6 8 10
print()

# =============================================================
# 7. 중첩 반복문 — for 안에 for
# =============================================================
# break / continue는 자신이 속한 반복문 하나에만 영향

for dan in range(2, 5):         # 2단 ~ 4단
    for num in range(1, 10):
        print(f"{dan} x {num} = {dan * num}")
    print()

# =============================================================
# 8. for-else / while-else
# =============================================================
# else 블록은 break 없이 반복이 정상 완료됐을 때만 실행됨

for i in range(5):
    print(i, end=" ")
else:
    print("\n정상 완료")        # break 없이 끝났으므로 실행

for i in range(5):
    if i == 3:
        break
else:
    print("이건 출력 안 됨")    # break로 빠져나왔으므로 실행 안 됨

# =============================================================
# 9. 리스트 컴프리헨션 — for 반복을 한 줄로
# =============================================================
# 형식: [표현식 for 변수 in 반복가능한것 if 조건]

squares = [x ** 2 for x in range(1, 6)]
print(squares)              # [1, 4, 9, 16, 25]

evens = [x for x in range(1, 11) if x % 2 == 0]
print(evens)                # [2, 4, 6, 8, 10]
