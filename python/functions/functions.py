# =============================================================
# 함수 (Functions)
# =============================================================
# 함수란 특정 작업을 수행하는 코드 블록에 이름을 붙인 것입니다.
# 같은 코드를 여러 번 작성하는 대신 함수를 호출해서 재사용합니다.

# =============================================================
# 1. 함수 정의와 호출
# =============================================================
# def 함수이름(매개변수):
#     실행할 코드

def greet():
    print("안녕하세요!")

greet()     # 안녕하세요!
greet()     # 안녕하세요! (여러 번 호출 가능)

# =============================================================
# 2. 매개변수 (Parameter) — 함수에 값 전달하기
# =============================================================
def greet_name(name):
    print(f"안녕하세요, {name}님!")

greet_name("Alice")     # 안녕하세요, Alice님!
greet_name("Bob")       # 안녕하세요, Bob님!

# 매개변수 여러 개
def add(a, b):
    print(a + b)

add(3, 5)               # 8
add(10, 20)             # 30

# =============================================================
# 3. return — 결과값 돌려주기
# =============================================================
def multiply(a, b):
    return a * b        # 호출한 곳으로 결과를 반환

result = multiply(4, 5)
print(result)           # 20

# return 없는 함수는 None을 반환
def no_return():
    print("반환값 없음")

val = no_return()
print(val)              # None

# 여러 값 반환 (튜플로 묶여서 반환됨)
def min_max(numbers):
    return min(numbers), max(numbers)

lo, hi = min_max([3, 1, 4, 1, 5, 9])
print(lo, hi)           # 1 9

# =============================================================
# 4. 기본값 매개변수 (Default Parameter)
# =============================================================
def power(base, exp=2):         # exp 기본값은 2
    return base ** exp

print(power(3))                 # 9  (3^2)
print(power(3, 3))              # 27 (3^3)

def introduce(name, age=0, city="미입력"):
    print(f"이름: {name}, 나이: {age}, 도시: {city}")

introduce("Alice", 20, "서울")  # 이름: Alice, 나이: 20, 도시: 서울
introduce("Bob", 25)            # 이름: Bob, 나이: 25, 도시: 미입력
introduce("Charlie")            # 이름: Charlie, 나이: 0, 도시: 미입력

# =============================================================
# 5. 키워드 인수 (Keyword Argument)
# =============================================================
# 매개변수 이름을 명시하면 순서에 상관없이 전달 가능
def book_info(title, author, year):
    print(f"[{year}] {title} - {author}")

book_info("파이썬 입문", "홍길동", 2023)
book_info(author="김철수", year=2024, title="알고리즘")  # 순서 달라도 OK

# =============================================================
# 6. 가변 인수 (*args) — 개수가 정해지지 않은 인수
# =============================================================
def total(*numbers):            # *args: 여러 값을 튜플로 받음
    result = 0
    for n in numbers:
        result += n
    return result

print(total(1, 2, 3))           # 6
print(total(10, 20, 30, 40))    # 100

# =============================================================
# 7. 가변 키워드 인수 (**kwargs)
# =============================================================
def print_info(**info):         # **kwargs: 키=값 형태를 딕셔너리로 받음
    for key, value in info.items():
        print(f"  {key}: {value}")

print_info(name="Alice", age=20, major="CS")
# name: Alice
# age: 20
# major: CS

# =============================================================
# 8. 스코프 (Scope) — 변수의 유효 범위
# =============================================================
x = 100             # 전역 변수 (Global)

def show_scope():
    y = 200         # 지역 변수 (Local) — 함수 안에서만 유효
    print(x)        # 전역 변수는 함수 안에서 읽기 가능
    print(y)

show_scope()
print(x)            # 100
# print(y)          # 오류! 지역 변수는 함수 밖에서 접근 불가

# =============================================================
# 9. 람다 함수 (Lambda) — 이름 없는 간단한 함수
# =============================================================
# 형식: lambda 매개변수: 반환값

square = lambda x: x ** 2
print(square(5))            # 25

add = lambda a, b: a + b
print(add(3, 4))            # 7

# 정렬할 때 자주 사용
students = [("Alice", 85), ("Bob", 92), ("Charlie", 78)]
students.sort(key=lambda s: s[1])       # 점수 기준 정렬
print(students)             # [('Charlie', 78), ('Alice', 85), ('Bob', 92)]

# =============================================================
# 10. 함수 안에 함수 (중첩 함수)
# =============================================================
def outer(x):
    def inner(y):           # outer 안에서만 사용 가능한 함수
        return y * 2
    return inner(x) + 1

print(outer(5))             # 11  (5*2 + 1)

# =============================================================
# 11. 재귀 함수 (Recursion) — 자기 자신을 호출
# =============================================================
def factorial(n):
    if n <= 1:              # 기저 조건 (반드시 있어야 무한루프 방지)
        return 1
    return n * factorial(n - 1)    # 자기 자신 호출

print(factorial(5))         # 120  (5 * 4 * 3 * 2 * 1)
print(factorial(10))        # 3628800
