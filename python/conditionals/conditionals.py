# =============================================================
# 조건문 (Conditionals)
# =============================================================
# 특정 조건에 따라 다른 코드를 실행할 때 사용합니다.
# Python은 들여쓰기(indent)로 블록을 구분합니다.

# =============================================================
# 1. if 문 — 조건이 참(True)일 때 실행
# =============================================================
score = 75

if score >= 60:
    print("합격")           # score가 60 이상이므로 실행됨

# =============================================================
# 2. if-else 문 — 참/거짓 두 가지 경우
# =============================================================
temperature = 15

if temperature >= 20:
    print("반팔을 입으세요")
else:
    print("긴팔을 입으세요")  # 15 < 20 이므로 이 줄 실행

# =============================================================
# 3. if-elif-else 문 — 여러 조건을 순서대로 검사
# =============================================================
score = 85

if score >= 90:
    grade = "A"
elif score >= 80:
    grade = "B"             # 85 >= 80 이므로 여기서 실행
elif score >= 70:
    grade = "C"
elif score >= 60:
    grade = "D"
else:
    grade = "F"

print(f"점수: {score}, 학점: {grade}")  # 점수: 85, 학점: B

# =============================================================
# 4. 비교 연산자
# =============================================================
a = 10
b = 20

print(a == b)   # False  (같다)
print(a != b)   # True   (다르다)
print(a < b)    # True   (작다)
print(a > b)    # False  (크다)
print(a <= b)   # True   (작거나 같다)
print(a >= b)   # False  (크거나 같다)

# =============================================================
# 5. 논리 연산자 (and, or, not)
# =============================================================
age = 20
has_ticket = True

# and: 둘 다 True여야 True
if age >= 18 and has_ticket:
    print("입장 가능")

# or: 하나라도 True면 True
is_holiday = False
is_weekend = True

if is_holiday or is_weekend:
    print("쉬는 날")

# not: True → False, False → True
is_raining = False

if not is_raining:
    print("산책하기 좋은 날")

# =============================================================
# 6. in 연산자 — 포함 여부 확인
# =============================================================
fruits = ["apple", "banana", "cherry"]

if "banana" in fruits:
    print("바나나 있음")

if "mango" not in fruits:
    print("망고 없음")

# 문자열에도 사용 가능
message = "Hello, Python!"

if "Python" in message:
    print("Python 언급됨")

# =============================================================
# 7. 중첩 if 문
# =============================================================
num = 15

if num > 0:
    print("양수입니다")
    if num % 2 == 0:
        print("짝수입니다")
    else:
        print("홀수입니다")   # 15는 홀수이므로 실행
else:
    print("0 또는 음수입니다")

# =============================================================
# 8. 조건부 표현식 (삼항 연산자)
# =============================================================
# 형식: 참일때값 if 조건 else 거짓일때값
x = 10
result = "양수" if x > 0 else "음수 또는 0"
print(result)   # 양수

# 홀짝 판별도 한 줄로
n = 7
print("짝수" if n % 2 == 0 else "홀수")   # 홀수
