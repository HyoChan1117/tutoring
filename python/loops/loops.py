# =============================================================
# 반복문 (Loops)
# =============================================================
# 같은 코드를 여러 번 실행할 때 사용합니다.
# Python의 반복문은 for와 while 두 가지입니다.

# =============================================================
# 1. for 문 — 정해진 횟수나 컬렉션을 순서대로 반복
# =============================================================

# 리스트 순회
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)
# apple
# banana
# cherry

# 문자열 순회 (한 글자씩)
for char in "Hello":
    print(char, end=" ")    # H e l l o  (end=" "로 줄바꿈 대신 공백)
print()                     # 줄 바꿈

# =============================================================
# 2. range() — 숫자 범위 반복
# =============================================================

# range(끝) → 0부터 끝-1까지
for i in range(5):
    print(i, end=" ")       # 0 1 2 3 4
print()

# range(시작, 끝) → 시작부터 끝-1까지
for i in range(1, 6):
    print(i, end=" ")       # 1 2 3 4 5
print()

# range(시작, 끝, 증가폭)
for i in range(0, 10, 2):
    print(i, end=" ")       # 0 2 4 6 8
print()

# 역순 반복
for i in range(5, 0, -1):
    print(i, end=" ")       # 5 4 3 2 1
print()

# =============================================================
# 3. enumerate() — 인덱스와 값을 함께 가져오기
# =============================================================
subjects = ["수학", "영어", "과학"]

for index, subject in enumerate(subjects):
    print(f"{index + 1}번: {subject}")
# 1번: 수학
# 2번: 영어
# 3번: 과학

# =============================================================
# 4. while 문 — 조건이 True인 동안 반복
# =============================================================
count = 0
while count < 5:
    print(count, end=" ")   # 0 1 2 3 4
    count += 1              # count를 증가시키지 않으면 무한루프!
print()

# 합계 구하기
total = 0
n = 1
while n <= 100:
    total += n
    n += 1
print(f"1~100 합계: {total}")   # 5050

# =============================================================
# 5. break — 반복문 즉시 종료
# =============================================================
numbers = [3, 7, 2, 9, 1, 5]

# 처음으로 5보다 큰 수를 찾으면 멈추기
for num in numbers:
    if num > 5:
        print(f"찾았다: {num}")  # 찾았다: 7
        break

# while에서 break
count = 0
while True:                     # 무한 루프
    count += 1
    if count == 3:
        break                   # count가 3이 되면 탈출
print(f"count: {count}")        # count: 3

# =============================================================
# 6. continue — 현재 회차 건너뛰고 다음 반복으로
# =============================================================

# 짝수만 출력
for i in range(1, 11):
    if i % 2 != 0:
        continue                # 홀수면 건너뜀
    print(i, end=" ")           # 2 4 6 8 10
print()

# =============================================================
# 7. 중첩 반복문 (Nested Loops)
# =============================================================

# 구구단 2단~4단
for dan in range(2, 5):
    for num in range(1, 10):
        print(f"{dan} x {num} = {dan * num}")
    print()                     # 단 사이 빈 줄

# =============================================================
# 8. else 절 — 반복이 break 없이 정상 완료됐을 때 실행
# =============================================================
for i in range(5):
    print(i, end=" ")
else:
    print("\n반복 완료!")        # break 없이 끝났으므로 실행

# break로 끝나면 else가 실행되지 않음
for i in range(5):
    if i == 3:
        break
else:
    print("이건 출력 안 됨")     # break로 빠져나왔으므로 실행 안 됨

# =============================================================
# 9. 리스트 컴프리헨션 — 반복문을 한 줄로 작성
# =============================================================

# 일반 for문으로 제곱 리스트 만들기
squares = []
for i in range(1, 6):
    squares.append(i ** 2)
print(squares)                  # [1, 4, 9, 16, 25]

# 컴프리헨션으로 동일하게
squares = [i ** 2 for i in range(1, 6)]
print(squares)                  # [1, 4, 9, 16, 25]

# 조건 포함
even_squares = [i ** 2 for i in range(1, 11) if i % 2 == 0]
print(even_squares)             # [4, 16, 36, 64, 100]
